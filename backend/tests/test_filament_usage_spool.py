"""Verbrauch je Filament und Spulen-Check (für das OrcaSlicer-Plugin, seit v1.1.40).

Die Formate sind die echten aus OrcaSlicer 2.4/2.5: In der .gcode.3mf stehen die
Gramm je Platte in slice_info.config, im G-code stehen sie am DATEIENDE
(„; filament used [g] = 0.00, 0.00, 111.26, …"), je Projekt-Filament ein Wert. Bis
v1.1.39 las Printloom nur den Kopf — die Gramm von Orca-Dateien waren unbekannt.

Der Spulen-Check nimmt das Fach, das auch die Farm nehmen würde (ams_match), und
die Restmenge aus `remain` (Prozent) × `tray_weight` (Gramm). Unbekannt bleibt
unbekannt — sonst sähe ein unvollständiger Check wie „reicht" aus.
"""
import zipfile

from app.services import print_file, rack_logic, spool_check

ORCA_HEAD = """; HEADER_BLOCK_START
; generated by OrcaSlicer 2.5.0 on 2026-11-08 at 20:00:00
; total layer number: 55
; max_z_height: 11.00
; HEADER_BLOCK_END

; CONFIG_BLOCK_START
; filament_colour = #D3B7A7;#D6001C;#0078BF;#000000;#00000000
; filament_type = PLA;PETG;PLA;PLA;PLA
; CONFIG_BLOCK_END
G28
G1 Z0.2 F600
G1 X100 Y100 E1
"""
ORCA_FOOT = """; filament used [mm] = 0.00, 0.00, 35043.45, 0.00, 0.00
; filament used [g] = 0.00, 0.00, 111.26, 0.00, 0.00
; filament cost = 0.00, 0.00, 2.78, 0.00, 0.00
"""

SLICE_INFO = """<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="printer_model_id" value="BL-P001"/>
    <filament id="3" tray_info_idx="GFA01" type="PLA" color="#0078BF" used_m="35.04" used_g="111.26" group_id="0"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <filament id="4" tray_info_idx="GFA01" type="PLA" color="#BB3D43" used_m="10.84" used_g="34.42" group_id="0"/>
  </plate>
</config>
"""


def _ams(*trays, unit="0"):
    """Bambu-Form des AMS-Blocks: ids als Strings, remain als Zahl, Gewicht als String."""
    return {"ams": [{"id": unit, "humidity": "4", "temp": "24.1", "tray": list(trays)}],
            "ams_exist_bits": "1", "tray_exist_bits": "f", "tray_now": "255", "version": 4}


def _tray(tid, ttype, color, remain, weight="1000"):
    return {"id": str(tid), "tray_type": ttype, "tray_color": color, "remain": remain,
            "tray_weight": weight, "tray_info_idx": "GFA01"}


# ── filament_usage ──────────────────────────────────────────────────────────────

def test_gcode_von_orca_gramm_stehen_am_ende(tmp_path):
    g = tmp_path / "plate.gcode"
    g.write_text(ORCA_HEAD + "G1 X1 Y1\n" * 5000 + ORCA_FOOT, encoding="utf-8")
    assert print_file.filament_usage(str(g), ".gcode") == [
        {"slot": 3, "type": "PLA", "color": "#0078BF", "grams": 111.26}]


def test_gcode_von_bambu_studio_gramm_im_kopf(tmp_path):
    g = tmp_path / "bambu.gcode"
    g.write_text("; HEADER_BLOCK_START\n; total filament weight [g] : 12.34,5.67\n"
                 "; HEADER_BLOCK_END\n; filament_type = PLA;PETG\n"
                 "; filament_colour = #FFFFFF;#000000\nG28\n", encoding="utf-8")
    assert print_file.filament_usage(str(g), ".gcode") == [
        {"slot": 1, "type": "PLA", "color": "#FFFFFF", "grams": 12.34},
        {"slot": 2, "type": "PETG", "color": "#000000", "grams": 5.67}]


def test_ohne_grammangabe_ist_der_verbrauch_unbekannt_nicht_null(tmp_path):
    g = tmp_path / "alt.gcode"
    g.write_text("; filament_type = PLA\nG28\nG1 X1\n", encoding="utf-8")
    assert print_file.filament_usage(str(g), ".gcode") == []


def test_3mf_liest_slice_info_je_platte(tmp_path):
    p = tmp_path / "projekt.gcode.3mf"
    with zipfile.ZipFile(p, "w") as z:
        z.writestr("Metadata/slice_info.config", SLICE_INFO)
        z.writestr("Metadata/plate_1.gcode", ORCA_HEAD + ORCA_FOOT)
        z.writestr("Metadata/plate_2.gcode", ORCA_HEAD + ORCA_FOOT)
    assert print_file.filament_usage(str(p), ".3mf", 1) == [
        {"slot": 3, "type": "PLA", "color": "#0078BF", "grams": 111.26}]
    assert print_file.filament_usage(str(p), ".3mf", 2)[0]["grams"] == 34.42


def test_3mf_ohne_slice_info_nimmt_den_gcode_darin(tmp_path):
    p = tmp_path / "roh.3mf"
    with zipfile.ZipFile(p, "w") as z:
        z.writestr("Metadata/plate_1.gcode", ORCA_HEAD + ORCA_FOOT)
    assert print_file.filament_usage(str(p), ".3mf")[0]["slot"] == 3


# ── spool_check ─────────────────────────────────────────────────────────────────

USAGE = [{"slot": 3, "type": "PLA", "color": "#0078BF", "grams": 111.26}]


def test_spule_reicht():
    r = spool_check.check(USAGE, _ams(_tray(0, "PLA", "0078BFFF", 50)))
    assert r["state"] == "ok"
    item = r["items"][0]
    assert item["label"] == "A1" and item["left_g"] == 500.0 and item["need_g"] == 111.3


def test_spule_reicht_nicht():
    r = spool_check.check(USAGE, _ams(_tray(2, "PLA", "0078BFFF", 8)))
    assert r["state"] == "short"
    assert r["items"][0]["label"] == "A3"
    assert r["items"][0]["left_g"] == 80.0


def test_restmenge_unbekannt_bei_spule_ohne_rfid():
    r = spool_check.check(USAGE, _ams(_tray(0, "PLA", "0078BFFF", -1)))
    assert r["state"] == "unknown"
    assert r["items"][0]["left_g"] is None


def test_kein_passendes_material_heisst_die_farm_pausiert():
    r = spool_check.check([{"slot": 1, "type": "PETG", "color": "#000000", "grams": 20.0}],
                          _ams(_tray(0, "PLA", "000000FF", 90)))
    assert r["state"] == "no_material"
    assert r["items"][0]["status"] == "no_material"


def test_zwei_filamente_im_selben_fach_zaehlen_zusammen():
    usage = [{"slot": 1, "type": "PLA", "color": "#0078BF", "grams": 300.0},
             {"slot": 2, "type": "PLA", "color": "#0078BF", "grams": 300.0}]
    r = spool_check.check(usage, _ams(_tray(0, "PLA", "0078BFFF", 50)))
    assert r["state"] == "short"
    assert r["items"][0]["need_g"] == 600.0
    assert r["items"][0]["filaments"] == [1, 2]


def test_zweites_ams_heisst_b():
    r = spool_check.check(USAGE, _ams(_tray(1, "PLA", "0078BFFF", 50), unit="1"))
    assert r["items"][0]["label"] == "B2"


def test_ohne_ams_daten_ist_alles_unbekannt():
    r = spool_check.check(USAGE, {})
    assert r["state"] == "unknown" and r["reason"] == "ams"


def test_ohne_verbrauch_ist_nichts_zu_pruefen():
    assert spool_check.check([], _ams(_tray(0, "PLA", "0078BFFF", 50)))["state"] == "unknown"


# ── rack_logic.storable ─────────────────────────────────────────────────────────

RACK = {"slot_height_mm": 50, "slots_per_rack": 6, "slot_tolerance_mm": 20,
        "magazine_slot": 6, "slot_stacked_pct": 50}


def test_passt_ins_regal():
    r = rack_logic.storable(60, RACK)
    assert r["ok"] is True and r["slots_needed"] == 1


def test_hoechstes_objekt_unter_dem_magazin():
    # 5 volle Fächer + die Hälfte des sechsten, weil darüber das Magazin liegt.
    assert rack_logic.storable(0, RACK)["max_height_mm"] == 275.0
    assert rack_logic.storable(280, RACK)["ok"] is False


def test_ohne_magazin_zaehlt_die_toleranz_ueber_dem_obersten_fach():
    assert rack_logic.storable(0, {**RACK, "magazine_slot": 0})["max_height_mm"] == 320.0
