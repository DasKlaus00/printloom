def _three_mf(path, plates=(1,)):
    with zipfile.ZipFile(path, "w") as z:
        for p in plates:
            z.writestr(f"Metadata/plate_{p}.gcode", GCODE)
        z.writestr("Metadata/slice_info.config",
                   "<config>" + "".join(
                       f'<plate><metadata key="index" value="{p}"/>'
                       f'<filament id="1" type="PLA" color="#0078BF" used_g="25.50"/></plate>'
                       for p in plates) + "</config>")
    return path.read_bytes()


# ── /info ───────────────────────────────────────────────────────────────────────

def test_info_liefert_grenzwerte_und_den_modellcode(client, db, farm, x1c):
    r = client.get("/api/slicer/info").json()
    assert r["api"] == slicer.API_VERSION
    assert r["limits"]["crash"] == {"z_limit_mm": 30.0, "x_margin_mm": 10.0, "x_max_mm": 256.0}
    assert r["limits"]["rack"]["max_height_mm"] == 275.0
    # Orca vergleicht den Modellcode mit dem Drucker-Profil (X1C = BL-P001).
    assert r["printers"] == [{"id": x1c.id, "name": "X1C", "model": "x1c", "dev_model": "BL-P001"}]


# ── /check ──────────────────────────────────────────────────────────────────────

def test_check_findet_die_kollisionszone(client, db, farm, x1c):
    r = client.post("/api/slicer/check", content=gzip.compress(GCODE.encode()),
                    headers={"Content-Encoding": "gzip"}).json()
    assert r["crash"]["crash_risk"] is True
    assert r["crash"]["hit_x_mm"] == 5.0 and r["crash"]["hit_z_mm"] == 40.0


def test_check_urteilt_wie_die_farm_ueber_die_hoehe(client, db, farm, x1c):
    r = client.post("/api/slicer/check", content=SAFE_GCODE.encode()).json()
    assert r["crash"]["crash_risk"] is False
    # 60 mm × 15 % Zuschlag = 69 mm → 1 Fach; dieselbe Rechnung wie beim Einreihen.
    assert r["height"]["height_mm"] == 69.0
    assert r["height"]["ok"] is True and r["height"]["slots_needed"] == 1


def test_check_meldet_zu_hoch_fuers_regal(client, db, farm, x1c, monkeypatch):
    monkeypatch.setattr(slicer.rack_store, "load", lambda: {**RACK, "slots_per_rack": 1, "magazine_slot": 1})
    r = client.post("/api/slicer/check", content=SAFE_GCODE.encode()).json()
    assert r["height"]["ok"] is False
    assert r["height"]["max_height_mm"] == 25.0


def test_check_prueft_die_spule_im_fach_der_farm(client, db, farm, x1c):
    r = client.post("/api/slicer/check", content=SAFE_GCODE.encode()).json()
    # 10 % von 1000 g = 100 g Rest, 25,5 g Bedarf → reicht.
    assert r["spool"]["state"] == "ok"
    assert r["spool"]["items"][0]["label"] == "A1"


def test_check_hinterlaesst_keine_datei(client, db, farm, x1c, monkeypatch):
    import glob
    import tempfile
    before = set(glob.glob(tempfile.gettempdir() + "/printloom_check_*"))
    client.post("/api/slicer/check", content=SAFE_GCODE.encode())
    assert set(glob.glob(tempfile.gettempdir() + "/printloom_check_*")) == before


def test_grosser_gepackter_gcode_kommt_ganz_an(client, db, farm, x1c):
    """Ein echter Platten-G-code hat Hunderttausende Zeilen; der Treffer steht hier
    ganz am Ende — er wird nur gefunden, wenn nichts beim Entpacken verloren geht."""
    big = SAFE_GCODE + "G1 X120 Y120 E3\n" * 300_000 + "G1 Z45\nG1 X250 Y10\n"
    r = client.post("/api/slicer/check", content=gzip.compress(big.encode()),
                    headers={"Content-Encoding": "gzip"}).json()
    assert r["crash"]["crash_risk"] is True and r["crash"]["hit_x_mm"] == 250.0


def test_gepackte_bombe_wird_gestoppt(client, db, farm, monkeypatch):
    monkeypatch.setattr(slicer, "MAX_BYTES", 10_000)
    r = client.post("/api/slicer/check", content=gzip.compress(b"0" * 5_000_000),
                    headers={"Content-Encoding": "gzip"})
    assert r.status_code == 413


