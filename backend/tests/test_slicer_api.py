# ── /upload ─────────────────────────────────────────────────────────────────────

def test_upload_legt_in_bibliothek_und_warteschlange(client, db, farm, x1c, tmp_path):
    body = _three_mf(tmp_path / "x.3mf")
    r = client.post("/api/slicer/upload", params={"filename": "Halter.gcode.3mf"},
                    content=body).json()
    row = db.query(UploadedFile).one()
    assert row.original_filename == "Halter.gcode.3mf" and row.file_type == ".3mf"
    assert r["file_id"] == row.id and r["queued"] is True
    # Dieselbe Job-Form wie „+ Warteschlange" in der Bibliothek (FileLibrary.jsx).
    jobs = autofarm._read_config(autofarm.QUEUE_PATH, {"jobs": []})["jobs"]
    assert jobs == [{"id": 1, "fileId": row.id, "fileName": "Halter.gcode.3mf", "slot": None,
                     "amsMap": "", "status": "pending", "plate": None, "plateTotal": None,
                     "plateName": None, "objectHeight": None, "progress": 0, "remaining": 0}]
    assert r["job_ids"] == [1]
    assert r["checks"][0]["crash"]["crash_risk"] is True


def test_mehrere_platten_ergeben_je_platte_einen_job(client, db, farm, x1c, tmp_path):
    body = _three_mf(tmp_path / "x.3mf", plates=(1, 2, 3))
    r = client.post("/api/slicer/upload", params={"filename": "Set.gcode.3mf"}, content=body).json()
    jobs = autofarm._read_config(autofarm.QUEUE_PATH, {"jobs": []})["jobs"]
    assert [(j["plate"], j["plateTotal"]) for j in jobs] == [(1, 3), (2, 3), (3, 3)]
    assert [c["plate"] for c in r["checks"]] == [1, 2, 3]


