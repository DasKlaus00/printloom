RACK = {"num_racks": 2, "slots_per_rack": 6, "slot_height_mm": 50, "slot_tolerance_mm": 20,
        "magazine_slot": 6, "slot_stacked_pct": 50, "height_margin_pct": 15.0,
        "slots": {"1-1": {"status": "free"}, "1-2": {"status": "done"}, "1-3": {"status": "ready"}}}

# Ein Platten-G-code wie aus Orca: Typen im Kopf, Gramm am Ende. Bei Z 40 fährt er
# auf X 5 — mitten in den 10-mm-Streifen, in dem der Arm am Bett vorbeifährt.
GCODE = """; HEADER_BLOCK_START
; generated by OrcaSlicer 2.5.0
; HEADER_BLOCK_END
; filament_colour = #0078BF;#D6001C
; filament_type = PLA;PETG
G28
G90
G1 Z0.2 F600
G1 X100 Y100 E1
G1 Z40
G1 X5 Y100
G1 Z60
G1 X120 Y120 E2
; filament used [g] = 25.50, 0.00
"""
SAFE_GCODE = GCODE.replace("G1 X5 Y100", "G1 X50 Y100")

AMS_RAW = {"ams": [{"id": "0", "tray": [
    {"id": "0", "tray_type": "PLA", "tray_color": "0078BFFF", "remain": 10, "tray_weight": "1000"}]}]}

REPORT = {"print": {"gcode_state": "RUNNING", "mc_percent": 42, "mc_remaining_time": 73,
                    "subtask_name": "Teil", "nozzle_temper": 219.8, "bed_temper": 55.0,
                    "nozzle_diameter": "0.4", "ams": AMS_RAW,
                    # Was NICHT nach Orca darf:
                    "fun": "3EC1AFFF9CFF", "ipcam": {"rtsp_url": "rtsps://10.0.0.5/streaming"},
                    "net": {"info": [{"ip": 12345}]}, "hms": [{"attr": 1}]}}


